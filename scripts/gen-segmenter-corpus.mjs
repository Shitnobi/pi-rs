#!/usr/bin/env node
// Generates crates/pi-tui/src/unicode/segmenter_corpus.rs — a golden corpus of
// the LIVE Intl.Segmenter's grapheme segmentations, built from the inputs of
// the official UCD 15.1 GraphemeBreakTest plus targeted extra cases.
//
// Why: the TS original uses Intl.Segmenter (ICU), and ICU is known to diverge
// from the published UCD test in places (e.g. U+2701 ZWJ U+2701: UCD expects
// one cluster, ICU breaks after the ZWJ). For 1:1 parity the runtime wins, so
// this corpus records what Intl.Segmenter actually does.
//
// Usage: node scripts/gen-segmenter-corpus.mjs > crates/pi-tui/src/unicode/segmenter_corpus.rs

import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const segmenter = new Intl.Segmenter(undefined, { granularity: "grapheme" });

function segments(s) {
	return [...segmenter.segment(s)].map((x) => x.segment);
}

function rustEscape(s) {
	let out = "";
	for (const ch of s) {
		const cp = ch.codePointAt(0);
		if (cp === 0x22) out += '\\"';
		else if (cp === 0x5c) out += "\\\\";
		else if (cp >= 0x20 && cp <= 0x7e) out += ch;
		else out += `\\u{${cp.toString(16)}}`;
	}
	return out;
}

// --- inputs from the official UCD test --------------------------------------

const text = readFileSync(join(HERE, "data", "GraphemeBreakTest.txt"), "utf8");
const inputs = [];
for (const line of text.split("\n")) {
	if (line.startsWith("#") || line.trim() === "") continue;
	const body = line.split("#")[0].trim();
	let s = "";
	let ucdExpected = [];
	let current = "";
	for (const tok of body.split(/\s+/)) {
		if (tok === "÷") {
			if (current) {
				ucdExpected.push(current);
				current = "";
			}
		} else if (tok === "×") {
			// continue
		} else {
			const ch = String.fromCodePoint(parseInt(tok, 16));
			s += ch;
			current += ch;
		}
	}
	if (current) ucdExpected.push(current);
	inputs.push({ input: s, ucdExpected });
}

// --- targeted extras: the shapes the width engine actually cares about ------

const extras = [
	"a\u0301", // base + combining mark
	"\u0e33", // Thai AM
	"\u0eb3", // Lao AM
	"e\u0301\u0301\u0301", // multiple marks
	"\ud83d\ude00\ud83d\ude00", // two astral emoji (JS escapes)
	"\ud83d\udc68\u200d\ud83d\udc69\u200d\ud83d\udc67\u200d\ud83d\udc66", // ZWJ family
	"\ud83c\uddfa\ud83c\uddf8\ud83c\uddfa\ud83c\uddf8", // two flag pairs
	"\ud83c\uddfa", // lone regional indicator
	"\uac00\u11a8", // precomposed LV + T
	"\u1100\u1161\u11a8", // decomposed L V T
	"\u0600abcd", // prepend (Arabic number sign)
	"a\u200db", // ZWJ between plain letters
	"\u2701\u200d\u2701", // UCD/ICU divergence case (scissors)
	"\ud83d\ude00\u200d\u2701", // ExtPict ZWJ non-ExtPict
	"\u2701\u200d\ud83d\ude00", // non-ExtPict ZWJ ExtPict
	"\ud83d\udc4d\ud83c\udffd", // thumbs up + skin tone
	"\ufe0f", // lone VS16
	"a\ufe0fb", // VS16 mid-string
	"\u302e", // Hangul single vowel tone mark
	"\u0930\u094d\u0930", // Devanagari ra virama ra (GB9c territory)
	"\u0d30\u0d4d\u0d30", // Malayalam ra virama ra
];
for (const s of extras) inputs.push({ input: s, ucdExpected: null });

// --- emit --------------------------------------------------------------------

const entries = [];
let diverged = 0;
for (const { input, ucdExpected } of inputs) {
	const got = segments(input);
	if (ucdExpected && (got.length !== ucdExpected.length || got.some((g, i) => g !== ucdExpected[i]))) {
		diverged++;
	}
	entries.push(`("${rustEscape(input)}", &["${got.map((g) => rustEscape(g)).join('", "')}"])`);

}

process.stderr.write(
	`${entries.length} cases, ${diverged} where ICU diverges from the UCD 15.1 expectation\n`,
);

console.log(`// @generated by scripts/gen-segmenter-corpus.mjs — DO NOT EDIT by hand.
// Golden corpus of the LIVE Intl.Segmenter (ICU) grapheme segmentations.
// Built from the UCD 15.1 GraphemeBreakTest inputs plus targeted extras.
// ICU is the ground truth: where it diverges from the published UCD test,
// this file records ICU's behavior (the TS original uses Intl.Segmenter).
#![allow(clippy::all)]

pub static CORPUS: &[(&str, &[&str])] = &[
${entries.join(",\n")},
];
`);
